#!/usr/bin/env python3
"""Source-shape ratchet: files and impl blocks may only shrink.

Defaults apply to every Rust file under `crates/`. Existing offenders are
listed in `scripts/code_shape_allowlist.txt` with their current size; the
check fails when one grows past that size. Remove an entry once the file or
impl drops below the default.

Usage:
    python scripts/check_code_shape.py
    python scripts/check_code_shape.py --write-allowlist  # manual, review the diff
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

DEFAULT_FILE_LIMIT = 1500
DEFAULT_IMPL_LIMIT = 800
ROOT = Path(__file__).resolve().parent.parent
ALLOWLIST = Path("scripts/code_shape_allowlist.txt")


def relative(path: Path) -> str:
    return path.relative_to(ROOT).as_posix()


def load_allowlist(path: Path) -> dict[tuple[str, str, str], int]:
    entries: dict[tuple[str, str, str], int] = {}
    if not path.exists():
        return entries
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        parts = line.split(maxsplit=3)
        if len(parts) < 3:
            raise SystemExit(f"bad allowlist line: {raw!r}")
        kind, file_name, limit = parts[0], parts[1], int(parts[2])
        name = parts[3] if kind == "impl" and len(parts) > 3 else ""
        entries[(kind, file_name, name)] = limit
    return entries


def scan_file(path: Path) -> tuple[int, list[tuple[str, int]]]:
    lines = path.read_text(encoding="utf-8").splitlines()
    impls: list[tuple[str, int]] = []
    index = 0
    while index < len(lines):
        line = lines[index]
        if line.startswith("impl ") and line.rstrip().endswith("{"):
            start = index
            depth = 0
            for end in range(index, len(lines)):
                depth += lines[end].count("{") - lines[end].count("}")
                if depth == 0 and end > start:
                    size = end - start + 1
                    if size > DEFAULT_IMPL_LIMIT:
                        impls.append((line.strip()[:-1].strip(), size))
                    index = end
                    break
        index += 1
    return len(lines), impls


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--write-allowlist",
        action="store_true",
        help="rewrite the allowlist with the current offenders",
    )
    args = parser.parse_args()

    allowlist = load_allowlist(ROOT / ALLOWLIST)
    offenders: list[tuple[str, str, str, int, int]] = []
    stale: list[tuple[str, str, str, int]] = []

    for path in sorted((ROOT / "crates").rglob("*.rs")):
        name = relative(path)
        lines, impls = scan_file(path)
        if lines > DEFAULT_FILE_LIMIT:
            key = ("file", name, "")
            limit = (
                DEFAULT_FILE_LIMIT
                if args.write_allowlist
                else allowlist.get(key, DEFAULT_FILE_LIMIT)
            )
            if lines > limit:
                offenders.append(("file", name, "", lines, limit))
            elif lines < DEFAULT_FILE_LIMIT:
                stale.append((*key, lines))
        for impl_name, size in impls:
            key = ("impl", name, impl_name)
            limit = (
                DEFAULT_IMPL_LIMIT
                if args.write_allowlist
                else allowlist.get(key, DEFAULT_IMPL_LIMIT)
            )
            if size > limit:
                offenders.append(("impl", name, impl_name, size, limit))
            elif size < DEFAULT_IMPL_LIMIT:
                stale.append((*key, size))

    if args.write_allowlist:
        rows = ["# Generated by scripts/check_code_shape.py --write-allowlist."]
        rows.append("# Remove an entry once the item drops below the default size.")
        for kind, name, impl_name, size, _ in sorted(offenders):
            if kind == "file":
                rows.append(f"file {name} {size}")
            else:
                rows.append(f"impl {name} {size} {impl_name}")
        (ROOT / ALLOWLIST).write_text("\n".join(rows) + "\n", encoding="utf-8")
        print(f"wrote {ALLOWLIST} with {len(offenders)} entries")
        return 0

    if offenders:
        for kind, name, impl_name, size, limit in offenders:
            label = name if kind == "file" else f"{name} :: {impl_name}"
            print(f"FAIL {label}: {size} lines > {limit}")
        return 1

    for kind, name, impl_name, size in stale:
        label = name if kind == "file" else f"{name} :: {impl_name}"
        print(f"NOTE {label}: {size} lines, allowlist entry can be removed")

    print("code shape ok")
    return 0


if __name__ == "__main__":
    sys.exit(main())
